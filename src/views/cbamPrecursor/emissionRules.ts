/** 按CN码前缀判断间接排放是否必填，忽略编码内的空格。 */
export function isIndirectEmissionRequired(cnCode?: string) {
  const code = cnCode?.replace(/\s+/g, '') || '';
  if (code.startsWith('72')) {
    return [
      '72022',
      '72023000',
      '72025000',
      '72027000',
      '72028000',
      '72029100',
      '72029200',
      '72029300',
      '720299',
      '72029910',
      '72029930',
      '72029980',
      '7204',
    ].some(prefix => code.startsWith(prefix));
  }
  return ![
    '7301',
    '7302',
    '730300',
    '7304',
    '7305',
    '7306',
    '7307',
    '7308',
    '730900',
    '7310',
    '731100',
    '7318',
    '7326',
    '7601',
    '7603',
    '7604',
    '7605',
    '7606',
    '7607',
    '7608',
    '76090000',
    '7610',
    '76110000',
    '7612',
    '76130000',
    '7614',
    '7616',
    '26011200',
  ].some(prefix => code.startsWith(prefix));
}
