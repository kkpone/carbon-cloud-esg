const buildPreviewItems = (
  industryCode: IndustryCode,
  year: string,
): IndustryTopItem[] => {
  const seed = INDUSTRY_SEEDS[industryCode];
  const yearOffset = year === '2023' ? 0.96 : year === '2022' ? 0.91 : 1;
  const scale = (value?: string) => {
    if (!value) return null;
    const parsed = Number(value);
    if (!Number.isFinite(parsed)) return value;
    return String(Math.round(parsed * yearOffset));
  };
  const disclosedCompanies = seed.companies.filter(item => item.disclosed);
  return disclosedCompanies.map((item, index) => ({
    rank: index + 1,
    industryCode,
    listed: item.listed,
    revenueBillionCny: item.revenue,
    marketCapBillionCny: item.marketCap ?? null,
    company: {
      companyId: item.id,
      name: item.name,
      shortName: item.shortName,
      industryCategory: seed.category,
      registeredRegion: item.region,
      labels: item.labels,
      securities: item.code
        ? [{ marketCode: item.market ?? null, code: item.code }]
        : [],
    },
    summary: {
      year,
      disclosed: item.disclosed,
      totalEmissions: item.disclosed ? scale(item.total) : null,
      scope1: item.disclosed ? scale(item.scope1) : null,
      scope2: item.disclosed ? scale(item.scope2) : null,
      scope2Basis: item.disclosed ? item.scope2Basis ?? 'unknown' : null,
      scope3: item.disclosed ? scale(item.scope3) : null,
      intensity: item.disclosed ? item.intensity ?? null : null,
      unit: 'tCO2e',
      intensityUnit: 'tCO2e/百万元',
    },
  }));
};

export const buildIndustryTopPreviewOverviews = (): IndustryOverview[] =>
  TOP_INDUSTRIES.map(({ code }) => {
    const seed = INDUSTRY_SEEDS[code];
    const disclosedCount = seed.companies.filter(item => item.disclosed).length;
    return {
      industryCode: code,
      companyCount: disclosedCount,
      disclosedCount,
      latestYear: PREVIEW_YEARS[0],
      availableYears: PREVIEW_YEARS,
      medianEmissions: seed.medianEmissions,
      medianUnit: 'tCO2e',
      updatedAt: PREVIEW_UPDATED_AT,
    };
  });

export const buildIndustryTopPreviewList = (
  industryCode: IndustryFilterValue = ALL_INDUSTRIES_VALUE,
  year = PREVIEW_YEARS[0],
): IndustryTopListResponse => {
  const activeYear = PREVIEW_YEARS.includes(year) ? year : PREVIEW_YEARS[0];
  const records =
    industryCode === ALL_INDUSTRIES_VALUE
      ? TOP_INDUSTRIES.flatMap(({ code }) =>
          buildPreviewItems(code, activeYear),
        )
          .sort(
            (a, b) =>
              Number(b.revenueBillionCny || 0) -
              Number(a.revenueBillionCny || 0),
          )
          .map((item, index) => ({ ...item, rank: index + 1 }))
      : buildPreviewItems(industryCode, activeYear);
  const disclosedCount = records.filter(item => item.summary.disclosed).length;
  return {
    industryCode,
    year: activeYear,
    availableYears: PREVIEW_YEARS,
    updatedAt: PREVIEW_UPDATED_AT,
    total: records.length,
    disclosedCount,
    medianEmissions:
      industryCode === ALL_INDUSTRIES_VALUE
        ? null
        : INDUSTRY_SEEDS[industryCode].medianEmissions,
    medianUnit: 'tCO2e',
    records,
    isPreview: true,
  };
};

export const isPreviewCompanyId = (companyId?: string | null) =>
  Boolean(companyId && companyId.startsWith('preview-'));

export const findPreviewCompanyById = (companyId: string) => {
  const entry = TOP_INDUSTRIES.map(({ code }) => {
    const seed = INDUSTRY_SEEDS[code];
    const company = seed.companies.find(item => item.id === companyId);
    return company
      ? { industryCode: code, category: seed.category, company }
      : null;
  }).find(Boolean);
  return entry || null;
};

export const buildPreviewCarbonData = (
  companyId: string,
  years?: string[],
): CarbonData | null => {
  const found = findPreviewCompanyById(companyId);
  if (!found) return null;
  const { category, company } = found;
  const activeYears = years?.length
    ? years.filter(year => PREVIEW_YEARS.includes(year))
    : PREVIEW_YEARS;
  const resolvedYears = activeYears.length ? activeYears : PREVIEW_YEARS;

  const metrics: Metric[] = [];
  if (company.disclosed) {
    resolvedYears.forEach(year => {
      const offset = year === '2023' ? 0.96 : year === '2022' ? 0.91 : 1;
      const scale = (raw?: string) => {
        if (!raw) return null;
        const parsed = Number(raw);
        if (!Number.isFinite(parsed)) return raw;
        return String(Math.round(parsed * offset));
      };
      const scaleDecimal = (raw?: string) => {
        if (!raw) return null;
        const parsed = Number(raw);
        if (!Number.isFinite(parsed)) return raw;
        return (parsed * offset).toFixed(2);
      };
      const scope2Name =
        company.scope2Basis === 'market'
          ? '范围二碳排放量（市场法）'
          : company.scope2Basis === 'location'
          ? '范围二碳排放量（位置法）'
          : '范围二碳排放量';
      if (company.total) {
        metrics.push({
          indicatorCode: 'PREVIEW_TOTAL_EMISSIONS',
          name: '温室气体排放总量（范围一+范围二）',
          categoryCode: 'EMISSIONS',
          categoryName: '碳排放量',
          marketCode: company.market || null,
          unit: 'tCO2e',
          statisticalPeriod: year,
          valueNumeric: scale(company.total),
        });
      }
      if (company.scope1) {
        metrics.push({
          indicatorCode: 'PREVIEW_SCOPE_1',
          name: '范围一碳排放量',
          categoryCode: 'EMISSIONS',
          categoryName: '碳排放量',
          marketCode: company.market || null,
          unit: 'tCO2e',
          statisticalPeriod: year,
          valueNumeric: scale(company.scope1),
        });
      }
      if (company.scope2) {
        metrics.push({
          indicatorCode: 'PREVIEW_SCOPE_2',
          name: scope2Name,
          categoryCode: 'EMISSIONS',
          categoryName: '碳排放量',
          marketCode: company.market || null,
          unit: 'tCO2e',
          statisticalPeriod: year,
          valueNumeric: scale(company.scope2),
        });
      }
      if (company.scope3) {
        metrics.push({
          indicatorCode: 'PREVIEW_SCOPE_3',
          name: '范围三碳排放量',
          categoryCode: 'EMISSIONS',
          categoryName: '碳排放量',
          marketCode: company.market || null,
          unit: 'tCO2e',
          statisticalPeriod: year,
          valueNumeric: scale(company.scope3),
        });
      }
      if (company.intensity) {
        metrics.push({
          indicatorCode: 'PREVIEW_INTENSITY',
          name: '单位营收碳排放强度',
          categoryCode: 'INTENSITY',
          categoryName: '碳排放强度',
          marketCode: company.market || null,
          unit: 'tCO2e/百万元',
          currency: 'CNY',
          statisticalPeriod: year,
          valueNumeric: scaleDecimal(company.intensity),
        });
      }
    });
  }

  return {
    company: {
      companyId: company.id,
      name: company.name,
      shortName: company.shortName,
      industryCategory: category,
      registeredRegion: company.region,
      labels: company.labels,
      securities: company.code
        ? [{ marketCode: company.market ?? null, code: company.code }]
        : [],
    },
    years: resolvedYears,
    availableYears: PREVIEW_YEARS,
    metrics,
    sources: [],
  };
};
